require_relative '../rest'
require_relative '../log'
require_relative '../ssh'
require_relative '../assert'
require_relative 'info'
require_relative 'terminal_formatter'
require 'openssl'

module Aspera
  module Cli
    # Provide hints on errors
    # Hints of a product are added by its bundle (`add`), when its code is loaded.
    class Hints
      # Well know issues that users may get
      ERROR_HINTS = [
        {
          exception:   Aspera::Rest::CallError,
          match:       /Signature has expired/,
          remediation: [
            'There is too much time difference between your computer and the server',
            'Check your local time: is time synchronization enabled?'
          ]
        },
        {
          exception:   OpenSSL::SSL::SSLError,
          match:       /(does not match the server certificate|certificate verify failed)/,
          remediation: [
            'You can ignore SSL errors with either of the following options:',
            '--insecure=yes  (global skip)',
            '--ignore-certificate=@list,https://<address>[:<port>]  (selective skip)'
          ]
        },
        {
          exception:   OpenSSL::PKey::RSAError,
          match:       /Neither PUB key nor PRIV key/,
          remediation: [
            'option: private_key expects a key PEM value, not path to file',
            'if you provide a path: prefix with @file:',
            'e.g. --private-key=@file:/path/to/key.pem'
          ]
        },
        {
          exception:   Aspera::Rest::CallError,
          match:       /Invalid subject\./,
          remediation: [
            'It seems that this user name is not registered on the server',
            'Check the user name and try again'
          ]
        },
        {
          exception:   OpenSSL::Cipher::CipherError,
          match:       /authentication tag already generated by cipher/,
          remediation: [
            'If using JRuby, refer to aspera-cli documentation.',
            'Look for "unsupported algorithm".'
          ]
        },
        {
          exception:   OpenSSL::SSL::SSLError,
          match:       /unexpected eof while reading/,
          remediation: [
            'Look at parameter ssl_options in http_options.',
            'Refer to the manual for more information.',
            %q{Try: --http-options=@json:'{"ssl_options":["IGNORE_UNEXPECTED_EOF"]}'}
          ]
        },
        {
          exception:   Aspera::Ssh::Error,
          match:       /Could not chdir to home directory/,
          remediation: [
            'home not created in Windows?'
          ]
        },
        {
          exception:   StandardError,
          match:       /1Password CLI failed.*(not currently signed in|no active session)/m,
          remediation: [
            'The 1Password CLI (`op`) has no active session',
            'Check with: op whoami',
            'Sign in with: eval $(op signin)',
            'or enable "Integrate with 1Password CLI" in the 1Password desktop application (Settings > Developer)'
          ]
        }
      ].freeze
      private_constant :ERROR_HINTS
      # Hints added by bundles, see `add`
      @added = []

      class << self
        # Add a hint, shown after the built-in hints that match the same error.
        # @param exception   [Class]                 Class of the error
        # @param match       [String, Regexp, Array] Message of the error (String: whole message), or a list of them
        # @param remediation [Array<String>]         Lines of the hint
        # @return [nil]
        def add(exception:, match:, remediation:)
          Aspera.assert_type(exception, Class) { 'exception' }
          Aspera.assert(Array(match).all? { |m| m.is_a?(String) || m.is_a?(Regexp) }) { 'hint match: String or Regexp' }
          Aspera.assert_array_all(remediation, String) { 'remediation' }
          @added.push({exception: exception, match: match, remediation: remediation}.freeze)
          nil
        end

        # @param error [Exception] exception object
        def hint_for(error, formatter)
          # Loop on known error hints
          (ERROR_HINTS + @added).each do |hint|
            next unless error.is_a?(hint[:exception])
            message = error.message
            matches = hint[:match]
            matches = Array(matches)
            matches.each do |m|
              case m
              when String
                next unless message.eql?(m)
              when Regexp
                next unless message.match?(m)
              else Aspera.error_unexpected_value(m) { 'hint match' }
              end
              hint[:remediation].each do |r|
                Log.log.info { "#{TerminalFormatter.hint} #{r}" }
              end
            end
          end
        end
      end
    end
  end
end
