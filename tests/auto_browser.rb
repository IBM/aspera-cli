# Automated browser script using Google Chrome (Ferrum) with HTTP fallback.
# Intercepts URLs opened by ascli (secrets, OAuth consent, etc.),
# renders the HTML/CSS in Chrome, fills the forms, and submits without human interaction.

# Names selected by the test, see `select_browser` in test_helpers.rb
# Preset of the test configuration file that holds the login credentials
login_preset = nil
# Names of generated secrets (see `generated_secret` in test_helpers.rb) entered on secret and consent pages
secret_name = nil
access_code_name = nil
usage = 'Usage: auto_browser.rb [--login-preset=<preset>] [--secret=<name>] [--access-code=<name>] <url>'
OptionParser.new do |opts|
  opts.banner = usage
  opts.on('--login-preset=PRESET', 'Preset with username and password for login pages') { |v| login_preset = v }
  opts.on('--secret=NAME', 'Generated secret entered on secret pages') { |v| secret_name = v }
  opts.on('--access-code=NAME', 'Generated secret entered as access code on consent and secret pages') { |v| access_code_name = v }
end.parse!

url_str = ARGV[0]
if url_str.nil? || url_str.empty?
  warn(usage)
  exit(1)
end

uri = URI.parse(url_str)

# Check if Ferrum (Chrome automation) is available
ferrum_available = false
begin
  require 'ferrum'
  ferrum_available = true
rescue LoadError
  ferrum_available = false
end

# Host names of the local test servers (mock IdP)
LOOPBACK_HOSTS = %w[127.0.0.1 localhost ::1].freeze

# Value of a secret generated by the test runner (see `generated_secret` in test_helpers.rb): no default in this script.
# Read only when a page needs it, so that external login pages work without it.
# @param name   [String, nil] Name of the secret, selected by the test
# @param option [String]      Option of this script that gives the name
# @return [String] Value
def generated_secret_value(name, option)
  raise "Option #{option} required by this page, see `select_browser`" if name.nil?
  path = Paths::SECRETS / name
  raise "Secret not generated: #{name}" unless path.exist?
  path.read
end

# Helper to type text slowly character by character
# @param element [Ferrum::Node] DOM element
# @param text    [String] Text to type
# @param delay   [Float] Average delay per character, each pause varies randomly by +/- 50%
def type_slowly(element, text, delay)
  element.focus
  if delay.positive?
    text.each_char do |char|
      element.type(char)
      sleep(delay * rand(0.5..1.5))
    end
  else
    element.type(text)
  end
end

# Check if a DOM element is visible and displayed to the user
# @param element [Ferrum::Node] DOM element
# @return [Boolean] true if the element is visible, false otherwise
def element_visible?(element)
  return false if element.nil?
  element.evaluate('this.offsetWidth > 0 && this.offsetHeight > 0') rescue false
end

# Retrieve login credentials (evaluated once) from the preset given with option `--login-preset`.
# Values in the preset may be extended values, e.g. a reference to a vault.
# @param preset [String, nil] Name of the preset, or nil if the test did not select one
# @return [Hash] Keys `:username` and `:password` with String values, empty if no preset
def login_credentials(preset)
  @login_credentials ||= LoginCredentials.read(preset)
end

# CSS selectors of a second factor or a captcha on a login page: they need a human, the test account shall not have them.
HUMAN_CHALLENGE_SELECTORS = [
  'input[autocomplete="one-time-code"]',
  'input[name*="otp" i]',
  'input[name*="totp" i]',
  'input[id*="otp" i]',
  'iframe[src*="recaptcha"]',
  'iframe[src*="hcaptcha"]'
].join(', ').freeze

# @param browser [Ferrum::Browser] Browser on a login page
# @return [Boolean] true if the page asks for a second factor or a captcha
def human_challenge?(browser)
  browser.css(HUMAN_CHALLENGE_SELECTORS).any? { |e| element_visible?(e) }
end

# Automate external OAuth login in browser (e.g. Aspera on Cloud / Faspex 5)
# @param browser      [Ferrum::Browser] Chrome browser instance
# @param target_uri   [URI] Target URL
# @param login_preset [String, nil] Preset holding the login credentials
# @param delay        [Float] Visual delay
# @param char_delay   [Float] Character delay
def automate_external_login(browser, target_uri, login_preset, delay, char_delay)
  params = Aspera::Rest.query_to_h(target_uri.query || '')
  redirect_uri_str = params['redirect_uri']
  return unless redirect_uri_str

  redirect_port = URI.parse(redirect_uri_str).port
  max_wait = (ENV['TEST_LOGIN_TIMEOUT'] || '120').to_i
  start_time = Time.now
  ibmid_clicked = false
  user_names = %w[email username userid]
  user_ids = %w[username userid user-name-input]
  # Values of attribute `type` of a text input (absent or empty: text)
  text_types = [nil, '', 'text']

  redirected = -> { browser.url.include?("localhost:#{redirect_port}") || browser.url.include?("127.0.0.1:#{redirect_port}") }
  loop do
    break if redirected.call
    break if Time.now - start_time > max_wait

    raise "Login page asks for a second factor or a captcha: use a test account without MFA (#{browser.url})" if human_challenge?(browser)

    # Automatically bypass Chrome SSL warning if present on local callback
    proceed_link = browser.at_css('#proceed-link')
    if proceed_link && element_visible?(proceed_link)
      proceed_link.click
      sleep(0.5)
    end

    # Automatically click "IBMid" button if present (e.g. on Aspera on Cloud login page)
    unless ibmid_clicked
      ibmid_btn = browser.xpath('//button[contains(translate(., "IBMD", "ibmd"), "ibmid")] | //a[contains(translate(., "IBMD", "ibmd"), "ibmid")] | //div[@role="button"][contains(translate(., "IBMD", "ibmd"), "ibmid")] | //div[contains(@class, "clickable")][contains(translate(., "IBMD", "ibmd"), "ibmid")] | //div[contains(@class, "ds-clickable")][contains(translate(., "IBMD", "ibmd"), "ibmid")]').find { |b| element_visible?(b) }
      if ibmid_btn
        sleep(delay) if delay.positive?
        ibmid_btn.click
        ibmid_clicked = true
        sleep(1)
      end
    end

    # Fill credentials from test configuration or vault if login fields are present
    creds = login_credentials(login_preset)

    # Passive/robust detection of visible inputs using offsetWidth/Height
    visible_inputs = browser.css('input').select { |i| element_visible?(i) }
    pass_field = visible_inputs.find { |i| i.attribute('type') == 'password' || i.attribute('name') == 'password' }

    # Step 1: enter username (and click Continue if two-step login like IBMid without visible password field)
    if creds[:username]
      user_field = visible_inputs.find { |i| user_names.include?(i.attribute('name')) || user_ids.include?(i.attribute('id')) || i.attribute('type') == 'email' }
      # Unknown names (e.g. Faspex 5 login page): first visible text input, other than the password
      user_field ||= visible_inputs.find { |i| text_types.include?(i.attribute('type')) && !i.equal?(pass_field) }
      if user_field
        if user_field.value.to_s.empty?
          type_slowly(user_field, creds[:username], char_delay)
          sleep(delay) if delay.positive?
        end
        unless pass_field
          next_btn = browser.css('button#continue-button, button[type="submit"], input[type="submit"]').find { |b| element_visible?(b) }
          next_btn ||= browser.xpath('//button[contains(translate(., "CONTINUEXTSAV", "continuextsav"), "continue") or contains(translate(., "CONTINUEXTSAV", "continuextsav"), "next") or contains(translate(., "CONTINUEXTSAV", "continuextsav"), "suivant")]').find { |b| element_visible?(b) }
          if next_btn
            next_btn.click
            sleep(1)
          end
        end
      end
    end

    # Step 2: enter password and submit when password field is visible
    if creds[:password] && pass_field
      if pass_field.value.to_s.empty?
        type_slowly(pass_field, creds[:password], char_delay)
        sleep(delay) if delay.positive?
      end
      submit_btn = browser.css('button#signinbutton, button[type="submit"], input[type="submit"], button#login-button').find { |b| element_visible?(b) } # cspell:disable-line
      submit_btn ||= browser.xpath('//button[contains(translate(., "SIGNLOGCO", "signlogco"), "sign in") or contains(translate(., "SIGNLOGCO", "signlogco"), "log in") or contains(translate(., "SIGNLOGCO", "signlogco"), "connexion")]').find { |b| element_visible?(b) }
      if submit_btn
        submit_btn.click
        sleep(1)
      end
    end

    sleep(0.5)
  end
  raise "Login not completed after #{max_wait}s, a human action is probably needed (check the credentials of option --login-preset). Page: #{browser.url}" unless redirected.call
end

# Automate page with Google Chrome via Ferrum
# @param target_uri   [URI] Target URL
# @param login_preset [String, nil] Preset holding the login credentials
# @param names        [Hash] Names of the generated secrets: `:secret`, `:access_code`
def automate_with_chrome(target_uri, login_preset, names)
  headless = ENV['TEST_HEADLESS'].to_s.eql?('true')
  # Default visual delay: 0.5s pause between actions (configurable with TEST_DELAY)
  delay = ENV.fetch('TEST_DELAY', headless ? '0' : '0.5').to_f
  char_delay = delay.positive? ? [delay / 20.0, 0.025].max : 0.0

  browser_options = {
    'no-sandbox'                => nil,
    'disable-gpu'               => nil,
    'ignore-certificate-errors' => nil,
    'allow-insecure-localhost'  => nil
  }
  browser = Ferrum::Browser.new(
    headless:        headless,
    slowmo:          delay.positive? ? 0.01 : 0.0, # cspell:disable-line
    timeout:         15,
    process_timeout: 15,
    browser_options: browser_options
  )

  browser.goto(target_uri.to_s)
  sleep(delay) if delay.positive?

  # Pages of the local mock servers are recognized by their path, only on a loopback address:
  # a real login page may have the same path (e.g. Faspex 5: `/aspera/faspex/auth/authorize`) and must be handled by `automate_external_login`
  local_path = LOOPBACK_HOSTS.include?(target_uri.hostname) ? target_uri.path : nil
  case local_path
  when %r{^/secret/}
    secret_input = browser.css('input[name="secret"]').find(&:focusable?)
    raise "Secret input not found on page #{target_uri}" unless secret_input

    access_code_input = browser.css('input[name="access_code"]').find(&:focusable?)
    if access_code_input
      type_slowly(access_code_input, generated_secret_value(names[:access_code], '--access-code'), char_delay)
      sleep(delay) if delay.positive?
    end

    type_slowly(secret_input, generated_secret_value(names[:secret], '--secret'), char_delay)
    sleep(delay) if delay.positive?

    submit_btn = browser.at_css('button.allow, button[type="submit"]')
    submit_btn&.click
    # Pause on the confirmation screen so the user can see it
    sleep(delay.positive? ? delay * 2 : 0.3)
  when %r{^/oauth/authorize}, %r{/auth/authorize}
    access_input = browser.css('input[name="consent_secret"]').find(&:focusable?)
    if access_input
      type_slowly(access_input, generated_secret_value(names[:access_code], '--access-code'), char_delay)
      sleep(delay) if delay.positive?
    end

    allow_btn = browser.at_css('button.allow, button[value="allow"], button[type="submit"]')
    allow_btn&.click
    sleep(delay.positive? ? delay * 2 : 0.3)
  else
    automate_external_login(browser, target_uri, login_preset, delay, char_delay)
  end
ensure
  browser&.quit
end

# Fallback HTTP submission using Aspera::Rest
# @param target_uri [URI]  Target URL
# @param names      [Hash] Names of the generated secrets: `:secret`, `:access_code`
def fallback_http(target_uri, names)
  # Local test servers (mock IdP) with a self-signed certificate: this function is called for loopback addresses only
  Aspera::Rest::Parameters.instance.session_cb = ->(session) { session.verify_mode = OpenSSL::SSL::VERIFY_NONE }
  api = Aspera::Rest::Client.new(base_url: "#{target_uri.scheme}://#{target_uri.host}:#{target_uri.port}")
  subpath = target_uri.path.delete_prefix('/')

  case target_uri.path
  when %r{^/secret/}
    _html, get_res = api.read(subpath, ret: :both, exception: false)
    unless get_res.code == '200'
      warn("Error: Expected 200 from secret page, got #{get_res.code}")
      exit(1)
    end

    form_data = {'secret' => generated_secret_value(names[:secret], '--secret'), 'decision' => 'submit'}
    form_data['access_code'] = generated_secret_value(names[:access_code], '--access-code') unless names[:access_code].nil?
    post_res = api.create(subpath, form_data, content_type: Aspera::Mime::WWW, exception: false, ret: :resp)
    unless %w[200 302].include?(post_res.code)
      warn("Error: Unexpected response after secret submit: #{post_res.code}")
      exit(1)
    end
  when %r{^/oauth/authorize}, %r{/auth/authorize}
    params = Aspera::Rest.query_to_h(target_uri.query || '')
    _html, get_res = api.read(subpath, params, ret: :both, exception: false)
    unless get_res.code == '200'
      warn("Error: Expected 200 from consent page, got #{get_res.code}")
      exit(1)
    end

    consent_params = {
      'client_id'             => params['client_id'],
      'redirect_uri'          => params['redirect_uri'],
      'state'                 => params['state'],
      'code_challenge'        => params['code_challenge'],
      'code_challenge_method' => params['code_challenge_method'],
      'decision'              => 'allow',
      'consent_secret'        => (names[:access_code] ? generated_secret_value(names[:access_code], '--access-code') : nil)
    }.compact

    post_res = api.create(subpath, consent_params, content_type: Aspera::Mime::WWW, exception: false, ret: :resp)
    unless %w[200 302].include?(post_res.code)
      warn("Error: Unexpected response after consent submit: #{post_res.code}")
      exit(1)
    end

    if post_res.code == '302' && post_res['Location']
      callback_uri = URI.parse(post_res['Location'])
      callback_api = Aspera::Rest::Client.new(base_url: "#{callback_uri.scheme}://#{callback_uri.host}:#{callback_uri.port}")
      callback_subpath = [callback_uri.path.delete_prefix('/'), callback_uri.query].compact.join('?')
      callback_api.call(operation: 'GET', subpath: callback_subpath, exception: false, ret: :resp)
    end
  end
end

# Open the URL with the system handler (default browser, or application registered for the scheme)
# @param target_uri [URI] URL to open
def open_with_system(target_uri)
  case RbConfig::CONFIG['host_os']
  when /darwin|mac os/ then system('open', target_uri.to_s)
  when /linux/ then system('xdg-open', target_uri.to_s)
  when /mswin|msys|mingw|cygwin/ then system('start', 'explorer', target_uri.to_s)
  end
end

secret_names = {secret: secret_name, access_code: access_code_name}
case
when !%w[http https].include?(uri.scheme)
  # Not a web page (e.g. `aspera://` to start IBM Aspera for Desktop): the registered application opens it.
  # In Chrome, the protocol handler asks for a confirmation that no one can give.
  open_with_system(uri)
when LOOPBACK_HOSTS.include?(uri.hostname)
  if ferrum_available
    begin
      automate_with_chrome(uri, login_preset, secret_names)
    rescue StandardError => e
      warn("Chrome automation failed (#{e.message}), falling back to HTTP")
      fallback_http(uri, secret_names)
    end
  else
    fallback_http(uri, secret_names)
  end
else
  # External/Remote OAuth login URL (e.g. Aspera on Cloud / Faspex 5)
  if ENV['TEST_INTERACTIVE'].to_s.eql?('manual')
    open_with_system(uri)
  elsif ferrum_available
    automate_with_chrome(uri, login_preset, secret_names)
  else
    warn("Auto-browser: gem ferrum is required to log in automatically at #{uri} (or use TEST_INTERACTIVE=manual)")
    exit(1)
  end
end
