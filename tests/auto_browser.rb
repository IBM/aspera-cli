# frozen_string_literal: true

require 'uri'
require 'optparse'
require 'aspera/environment'
require 'aspera/rest'
require 'aspera/mime'
require_relative '../build/lib/paths'

# Automated browser script using Google Chrome (Ferrum) with HTTP fallback.
# Intercepts URLs opened by ascli (secrets, OAuth consent, etc.),
# renders the HTML/CSS in Chrome, fills the forms, and submits without human interaction.

# Names selected by the test, see `select_browser` in test_helpers.rb
# Preset of the test configuration file that holds the login credentials
login_preset = nil
# Names of generated secrets (see `generated_secret` in test_helpers.rb) entered on secret and consent pages
secret_name = nil
access_code_name = nil
usage = 'Usage: auto_browser.rb [--login-preset=<preset>] [--secret=<name>] [--access-code=<name>] <url>'
OptionParser.new do |opts|
  opts.banner = usage
  opts.on('--login-preset=PRESET', 'Preset with username and password for login pages') { |v| login_preset = v }
  opts.on('--secret=NAME', 'Generated secret entered on secret pages') { |v| secret_name = v }
  opts.on('--access-code=NAME', 'Generated secret entered as access code on consent and secret pages') { |v| access_code_name = v }
end.parse!

url_str = ARGV[0]
if url_str.nil? || url_str.empty?
  warn(usage)
  exit(1)
end

uri = URI.parse(url_str)

# Check if Ferrum (Chrome automation) is available
ferrum_available = false
begin
  require 'ferrum'
  ferrum_available = true
rescue LoadError
  ferrum_available = false
end

# Value of a secret generated by the test runner (see `generated_secret` in test_helpers.rb): no default in this script.
# Read only when a page needs it, so that external login pages work without it.
# @param name   [String, nil] Name of the secret, selected by the test
# @param option [String]      Option of this script that gives the name
# @return [String] Value
def generated_secret_value(name, option)
  raise "Option #{option} required by this page, see `select_browser`" if name.nil?
  path = Paths::SECRETS / name
  raise "Secret not generated: #{name}" unless path.exist?
  path.read
end

# Helper to type text slowly character by character
# @param element [Ferrum::Node] DOM element
# @param text    [String] Text to type
# @param delay   [Float] Delay per character
def type_slowly(element, text, delay)
  element.focus
  if delay.positive?
    text.each_char do |char|
      element.type(char)
      sleep(delay)
    end
  else
    element.type(text)
  end
end

# Check if a DOM element is visible and displayed to the user
# @param element [Ferrum::Node] DOM element
# @return [Boolean] true if the element is visible, false otherwise
def element_visible?(element)
  return false if element.nil?
  element.evaluate('this.offsetWidth > 0 && this.offsetHeight > 0') rescue false
end

# Read one value of a preset using ascli itself: all extended values are evaluated by ascli
# (`@vault:`, `@file:`, `@extend:`, `@preset:`...), with the same home and config file as the tests.
# @param preset [String] Name of the preset in the test configuration file
# @param key    [String] Name of the value in the preset
# @return [String, nil] Evaluated value, or nil if not found
def preset_value(preset, key)
  stdout, _stderr, status = Aspera::Environment.secure_execute(
    File.join(Paths::BIN, 'ascli'), "--home=#{Paths::TMP / 'ascli_home'}", '--interactive=no', 'config', 'echo', "@preset:#{preset}.#{key}",
    mode:       :capture,
    exception:  false,
    stdin_data: ''
  )
  status.success? && !stdout.empty? ? stdout.chomp : nil
end

# Retrieve login credentials (evaluated once) from the preset given with option `--login-preset`.
# Values in the preset may be extended values, e.g. a reference to a vault.
# @param preset [String, nil] Name of the preset, or nil if the test did not select one
# @return [Hash] Keys `:username` and `:password` with String values, empty if no preset
def login_credentials(preset)
  @login_credentials ||=
    if preset.nil?
      {}
    else
      {username: preset_value(preset, 'username'), password: preset_value(preset, 'password')}.compact
    end
end

# Automate page with Google Chrome via Ferrum
# @param target_uri   [URI] Target URL
# @param login_preset [String, nil] Preset holding the login credentials
# @param names        [Hash] Names of the generated secrets: `:secret`, `:access_code`
def automate_with_chrome(target_uri, login_preset, names)
  headless = ENV['TEST_HEADLESS'].to_s.eql?('true')
  # Default visual delay: 0.5s pause between actions (configurable with TEST_DELAY)
  delay = ENV.fetch('TEST_DELAY', headless ? '0' : '0.5').to_f
  char_delay = delay.positive? ? [delay / 10.0, 0.05].max : 0.0

  browser = Ferrum::Browser.new(
    headless:        headless,
    slowmo:          delay.positive? ? 0.01 : 0.0,
    timeout:         15,
    process_timeout: 15,
    browser_options: {'no-sandbox' => nil, 'disable-gpu' => nil}
  )

  browser.goto(target_uri.to_s)
  sleep(delay) if delay.positive?

  case target_uri.path
  when %r{^/secret/}
    secret_input = browser.css('input[name="secret"]').find(&:focusable?)
    raise "Secret input not found on page #{target_uri}" unless secret_input

    access_code_input = browser.css('input[name="access_code"]').find(&:focusable?)
    if access_code_input
      type_slowly(access_code_input, generated_secret_value(names[:access_code], '--access-code'), char_delay)
      sleep(delay) if delay.positive?
    end

    type_slowly(secret_input, generated_secret_value(names[:secret], '--secret'), char_delay)
    sleep(delay) if delay.positive?

    submit_btn = browser.at_css('button.allow, button[type="submit"]')
    submit_btn&.click
    # Pause on the confirmation screen so the user can see it
    sleep(delay.positive? ? delay * 2 : 0.3)
  when %r{^/oauth/authorize}
    access_input = browser.css('input[name="consent_secret"]').find(&:focusable?)
    if access_input
      type_slowly(access_input, generated_secret_value(names[:access_code], '--access-code'), char_delay)
      sleep(delay) if delay.positive?
    end

    allow_btn = browser.at_css('button.allow, button[value="allow"], button[type="submit"]')
    allow_btn&.click
    sleep(delay.positive? ? delay * 2 : 0.3)
  else
    # External URL (e.g. SaaS OAuth login on api.ibmaspera.com):
    # Wait until redirected back to localhost/loopback callback server
    params = Aspera::Rest.query_to_h(target_uri.query || '')
    redirect_uri_str = params['redirect_uri']
    if redirect_uri_str
      redirect_port = URI.parse(redirect_uri_str).port
      max_wait = (ENV['TEST_LOGIN_TIMEOUT'] || '120').to_i
      start_time = Time.now
      w3id_clicked = false
      w3id_pwd_clicked = false
      user_names = %w[email username userid]
      user_ids = %w[username userid user-name-input]

      loop do
        break if browser.url.include?("localhost:#{redirect_port}") || browser.url.include?("127.0.0.1:#{redirect_port}")
        break if Time.now - start_time > max_wait

        # Automatically click "w3id (IBM)" button if present
        unless w3id_clicked
          w3id_btn = browser.xpath('//button[contains(translate(., "W", "w"), "w3id")] | //a[contains(translate(., "W", "w"), "w3id")] | //div[@role="button"][contains(translate(., "W", "w"), "w3id")] | //div[contains(@class, "clickable")][contains(translate(., "W", "w"), "w3id")] | //div[contains(@class, "ds-clickable")][contains(translate(., "W", "w"), "w3id")]').first
          if w3id_btn
            sleep(delay) if delay.positive?
            w3id_btn.click
            w3id_clicked = true
            sleep(1)
          end
        end

        # Automatically click "Mot de passe w3id" / "w3id password" button if present (after entering IBMid)
        unless w3id_pwd_clicked
          w3id_pwd_btn = browser.xpath('//div[@id="credsDiv"] | //*[@id="credentialSignin"] | //div[@role="button" or contains(@class, "clickable")][contains(translate(., "WMP", "wmp"), "w3id") and (contains(translate(., "WMP", "wmp"), "mot de passe") or contains(translate(., "WMP", "wmp"), "password"))]').first
          if element_visible?(w3id_pwd_btn)
            sleep(delay) if delay.positive?
            w3id_pwd_btn.click
            w3id_pwd_clicked = true
            sleep(1)
          end
        end

        # Fill credentials from test configuration or vault if login fields are present
        creds = login_credentials(login_preset)

        # Passive/robust detection of visible inputs using offsetWidth/Height
        visible_inputs = browser.css('input').select { |i| element_visible?(i) }

        if creds[:username]
          user_field = visible_inputs.find { |i| user_names.include?(i.attribute('name')) || user_ids.include?(i.attribute('id')) || i.attribute('type') == 'email' }
          if user_field && user_field.value.to_s.empty?
            type_slowly(user_field, creds[:username], char_delay)
            sleep(delay) if delay.positive?
            # If a password field is also visible, do not submit yet; let the password block fill it first
            pass_field_visible = visible_inputs.any? { |i| i.attribute('type') == 'password' || i.attribute('name') == 'password' }
            unless pass_field_visible
              next_btn = browser.css('button#continue-button, button[type="submit"]').find { |b| element_visible?(b) }
              next_btn&.click
              sleep(1)
            end
          end
        end

        if creds[:password]
          pass_field = visible_inputs.find { |i| i.attribute('type') == 'password' || i.attribute('name') == 'password' }
          if pass_field && pass_field.value.to_s.empty?
            type_slowly(pass_field, creds[:password], char_delay)
            sleep(delay) if delay.positive?
            submit_btn = browser.css('button#signinbutton, button[type="submit"], input[type="submit"], button#login-button').find { |b| element_visible?(b) }
            submit_btn&.click
            sleep(1)
          end
        end

        sleep(0.5)
      end
    end
  end
ensure
  browser&.quit
end

# Fallback HTTP submission using Aspera::Rest
# @param target_uri [URI]  Target URL
# @param names      [Hash] Names of the generated secrets: `:secret`, `:access_code`
def fallback_http(target_uri, names)
  api = Aspera::Rest::Client.new(base_url: "#{target_uri.scheme}://#{target_uri.host}:#{target_uri.port}")
  subpath = target_uri.path.delete_prefix('/')

  case target_uri.path
  when %r{^/secret/}
    _html, get_res = api.read(subpath, ret: :both, exception: false)
    unless get_res.code == '200'
      warn("Error: Expected 200 from secret page, got #{get_res.code}")
      exit(1)
    end

    form_data = {'secret' => generated_secret_value(names[:secret], '--secret'), 'decision' => 'submit'}
    form_data['access_code'] = generated_secret_value(names[:access_code], '--access-code') unless names[:access_code].nil?
    post_res = api.create(subpath, form_data, content_type: Aspera::Mime::WWW, exception: false, ret: :resp)
    unless %w[200 302].include?(post_res.code)
      warn("Error: Unexpected response after secret submit: #{post_res.code}")
      exit(1)
    end
  when %r{^/oauth/authorize}
    params = Aspera::Rest.query_to_h(target_uri.query || '')
    _html, get_res = api.read(subpath, params, ret: :both, exception: false)
    unless get_res.code == '200'
      warn("Error: Expected 200 from consent page, got #{get_res.code}")
      exit(1)
    end

    consent_params = {
      'client_id'             => params['client_id'],
      'redirect_uri'          => params['redirect_uri'],
      'state'                 => params['state'],
      'code_challenge'        => params['code_challenge'],
      'code_challenge_method' => params['code_challenge_method'],
      'decision'              => 'allow',
      'consent_secret'        => generated_secret_value(names[:access_code], '--access-code')
    }.compact

    post_res = api.create(subpath, consent_params, content_type: Aspera::Mime::WWW, exception: false, ret: :resp)
    unless %w[200 302].include?(post_res.code)
      warn("Error: Unexpected response after consent submit: #{post_res.code}")
      exit(1)
    end
  end
end

secret_names = {secret: secret_name, access_code: access_code_name}
case uri.host
when '127.0.0.1', 'localhost', '::1'
  if ferrum_available
    begin
      automate_with_chrome(uri, login_preset, secret_names)
    rescue StandardError => e
      warn("Chrome automation failed (#{e.message}), falling back to HTTP")
      fallback_http(uri, secret_names)
    end
  else
    fallback_http(uri, secret_names)
  end
else
  # External/Remote OAuth login URL (e.g. Aspera on Cloud / Faspex 5)
  if ENV['TEST_INTERACTIVE'].to_s.eql?('manual')
    case RbConfig::CONFIG['host_os']
    when /darwin|mac os/ then system('open', uri.to_s)
    when /linux/ then system('xdg-open', uri.to_s)
    when /mswin|msys|mingw|cygwin/ then system('start', 'explorer', uri.to_s)
    end
  elsif ferrum_available
    automate_with_chrome(uri, login_preset, secret_names)
  else
    warn("Auto-browser: skipping external GUI browser for #{uri}")
  end
end
